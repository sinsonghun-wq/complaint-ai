def normalize(name: str | None) -> str | None:
    """카테고리 이름을 지금 7종 이름으로 바꿉니다. 예전 이름도 받습니다. 7종이 아니면 None."""
    key = (name or "").strip()
    key = LEGACY.get(key, key)
    return key if key in BY_NAME else None


def prompt_block() -> str:
    """LLM 분석 프롬프트에 넣는 '카테고리 정의' 블록."""
    lines = [f"[카테고리 정의 - {len(CATEGORIES)}종]"]
    for c in CATEGORIES:
        lines.append(f"- {c.name}({c.department}): {c.summary}")
    return "\n".join(lines)
